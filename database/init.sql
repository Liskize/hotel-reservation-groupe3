-- 1. TABLE HOTELS
CREATE TABLE IF NOT EXISTS hotels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    ville VARCHAR(100) NOT NULL,
    adresse VARCHAR(255) NOT NULL,
    etoiles INTEGER NOT NULL
        CHECK (etoiles BETWEEN 0 AND 5),
    nb_chambres INTEGER NOT NULL
        CHECK (nb_chambres > 0),

    CONSTRAINT uq_hotels_nom_ville UNIQUE (nom, ville)
);

-- 2. TABLE CLIENTS
CREATE TABLE IF NOT EXISTS clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    telephone VARCHAR(30) NOT NULL
);

-- 3. TABLE RESERVATIONS
CREATE TABLE IF NOT EXISTS reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    client_id INTEGER NOT NULL,
    hotel_id INTEGER NOT NULL,

    date_arrivee DATE NOT NULL,
    date_depart DATE NOT NULL,

    nb_personnes INTEGER NOT NULL
        CHECK (nb_personnes > 0),

    statut VARCHAR(30) NOT NULL
        DEFAULT 'EN_ATTENTE'
        CHECK (
            statut IN (
                'EN_ATTENTE',
                'CONFIRMEE',
                'ANNULEE'
            )
        ),

    created_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reservation_client
        FOREIGN KEY (client_id)
        REFERENCES clients(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_reservation_hotel
        FOREIGN KEY (hotel_id)
        REFERENCES hotels(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_dates_reservation
        CHECK (date_depart > date_arrivee),

    CONSTRAINT uq_reservation
        UNIQUE (
            client_id,
            hotel_id,
            date_arrivee,
            date_depart
        )
);

-- Index pour les recherches fréquentes
CREATE INDEX IF NOT EXISTS idx_reservations_hotel
    ON reservations(hotel_id);

CREATE INDEX IF NOT EXISTS idx_reservations_client
    ON reservations(client_id);

CREATE INDEX IF NOT EXISTS idx_reservations_statut
    ON reservations(statut);
